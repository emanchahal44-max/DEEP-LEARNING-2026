class Generator(nn.Module):
    def __init__(self, latent_dim):
        super().__init__()
        self.model = nn.Sequential(
            nn.Linear(latent_dim, 256), nn.LeakyReLU(0.2),
            nn.Linear(256, 512),        nn.LeakyReLU(0.2),
            nn.Linear(512, 784),        nn.Tanh()
        )
    def forward(self, z): return self.model(z).view(z.size(0), 1, 28, 28)

class Discriminator(nn.Module):
    def __init__(self):
        super().__init__()
        self.model = nn.Sequential(
            nn.Linear(784, 512), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(512, 256), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(256, 1),   nn.Sigmoid()
        )
    def forward(self, x): return self.model(x.view(x.size(0), -1))

def train_gan(generator, discriminator, loader, epochs, latent_dim, g_opt, d_opt, label):
    criterion = nn.BCELoss()
    g_losses, d_losses = [], []
    print(f"\n{'='*50}\nTraining: {label}\n{'='*50}")
    for epoch in range(epochs):
        g_ep = d_ep = 0
        for real_images, _ in loader:
            bs = real_images.size(0)
            real_images = real_images.to(device)
            real_labels = torch.full((bs, 1), 0.9).to(device)
            fake_labels = torch.zeros(bs, 1).to(device)

            # Train D once
            d_opt.zero_grad()
            noise = torch.randn(bs, latent_dim).to(device)
            fakes = generator(noise)
            d_loss = criterion(discriminator(real_images), real_labels) + \
                     criterion(discriminator(fakes.detach()), fake_labels)
            d_loss.backward(); d_opt.step()

            # Train G twice
            for _ in range(2):
                g_opt.zero_grad()
                noise2 = torch.randn(bs, latent_dim).to(device)
                g_loss = criterion(discriminator(generator(noise2)),
                                   torch.ones(bs, 1).to(device))
                g_loss.backward(); g_opt.step()

            g_ep += g_loss.item(); d_ep += d_loss.item()

        avg_g = g_ep / len(loader); avg_d = d_ep / len(loader)
        g_losses.append(avg_g); d_losses.append(avg_d)
        print(f"Epoch [{epoch+1:3d}/{epochs}] | D Loss: {avg_d:.4f} | G Loss: {avg_g:.4f}")
    return g_losses, d_losses

latent_dim = 100
gen = Generator(latent_dim).to(device)
dis = Discriminator().to(device)
g_opt = optim.Adam(gen.parameters(), lr=0.0003, betas=(0.5, 0.999))
d_opt = optim.Adam(dis.parameters(), lr=0.0001, betas=(0.5, 0.999))

g_base, d_base = train_gan(gen, dis, train_loader, epochs=30,
    latent_dim=latent_dim, g_opt=g_opt, d_opt=d_opt, label="Base GAN FC 30 Epochs")
plot_losses(g_base, d_base, "Base GAN Loss Curve")
visualize_images(gen, latent_dim, "Base GAN Generated Images Epoch 30")


