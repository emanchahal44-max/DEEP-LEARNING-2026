def plot_losses(g_losses, d_losses, title, ymax=2.5):
    plt.figure(figsize=(8, 4))
    plt.plot(g_losses, label='Generator Loss',     color='blue')
    plt.plot(d_losses, label='Discriminator Loss', color='red')
    plt.title(title); plt.xlabel('Epoch'); plt.ylabel('Loss')
    plt.ylim(0, ymax); plt.legend(); plt.tight_layout()
    plt.savefig(title.replace(' ','_')+".png", dpi=150, bbox_inches='tight')
    plt.show()

def visualize_images(generator, latent_dim, title, dc=False):
    generator.eval()
    with torch.no_grad():
        noise = torch.randn(16, latent_dim, 1, 1).to(device) if dc \
                else torch.randn(16, latent_dim).to(device)
        imgs = generator(noise).cpu()
    fig, axes = plt.subplots(2, 8, figsize=(16, 4))
    for i, ax in enumerate(axes.flatten()):
        ax.imshow(imgs[i].squeeze(), cmap="gray"); ax.axis("off")
    fig.suptitle(title, fontsize=13); plt.tight_layout()
    plt.savefig(title.replace(' ','_')+".png", dpi=150, bbox_inches='tight')
    plt.show()
    generator.train()

