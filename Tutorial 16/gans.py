transform_dc = transforms.Compose([
    transforms.Resize(32), transforms.ToTensor(),
    transforms.Normalize((0.5,), (0.5,))
])
train_ds_dc = datasets.MNIST(root="./data", train=True, transform=transform_dc, download=True)
train_ld_dc = DataLoader(train_ds_dc, batch_size=128, shuffle=True, drop_last=True)

def weights_init(m):
    classname = m.__class__.__name__
    if classname.find('Conv') != -1:
        nn.init.normal_(m.weight.data, 0.0, 0.02)
    elif classname.find('BatchNorm') != -1:
        nn.init.normal_(m.weight.data, 1.0, 0.02)
        nn.init.constant_(m.bias.data, 0)

class DCGenerator(nn.Module):
    def __init__(self):
        super().__init__()
        self.net = nn.Sequential(
            # 1x1 -> 4x4
            nn.ConvTranspose2d(100, 256, 4, 1, 0, bias=False),
            nn.BatchNorm2d(256), nn.ReLU(True),
            # 4x4 -> 8x8
            nn.ConvTranspose2d(256, 128, 4, 2, 1, bias=False),
            nn.BatchNorm2d(128), nn.ReLU(True),
            # 8x8 -> 16x16
            nn.ConvTranspose2d(128, 64, 4, 2, 1, bias=False),
            nn.BatchNorm2d(64), nn.ReLU(True),
            # 16x16 -> 32x32
            nn.ConvTranspose2d(64, 1, 4, 2, 1, bias=False),
            nn.Tanh()
        )
    def forward(self, z): return self.net(z)

class DCDiscriminator(nn.Module):
    def __init__(self):
        super().__init__()
        # Spectral norm on every conv layer — prevents D from becoming too powerful
        self.net = nn.Sequential(
            nn.utils.spectral_norm(nn.Conv2d(1, 64, 4, 2, 1, bias=False)),
            nn.LeakyReLU(0.2, inplace=True),
            nn.utils.spectral_norm(nn.Conv2d(64, 128, 4, 2, 1, bias=False)),
            nn.LeakyReLU(0.2, inplace=True),
            nn.utils.spectral_norm(nn.Conv2d(128, 256, 4, 2, 1, bias=False)),
            nn.LeakyReLU(0.2, inplace=True),
            nn.utils.spectral_norm(nn.Conv2d(256, 1, 4, 1, 0, bias=False)),
            nn.Sigmoid()
        )
    def forward(self, x): return self.net(x).view(-1, 1)

def train_dcgan(generator, discriminator, loader, epochs, g_opt, d_opt, label):
    criterion = nn.BCELoss()
    g_losses, d_losses = [], []
    print(f"\n{'='*50}\nTraining: {label}\n{'='*50}")
    for epoch in range(epochs):
        g_ep = d_ep = 0
        for real_images, _ in loader:
            bs = real_images.size(0)
            real_images = real_images.to(device)
            real_labels = torch.full((bs, 1), 0.9).to(device)
            fake_labels = torch.zeros(bs, 1).to(device)

            noise = torch.randn(bs, 100, 1, 1).to(device)
            fakes = generator(noise)

            # Train D once
            d_opt.zero_grad()
            d_loss = criterion(discriminator(real_images), real_labels) + \
                     criterion(discriminator(fakes.detach()), fake_labels)
            d_loss.backward(); d_opt.step()

            # Train G twice
            for _ in range(2):
                g_opt.zero_grad()
                noise2 = torch.randn(bs, 100, 1, 1).to(device)
                g_loss = criterion(discriminator(generator(noise2)),
                                   torch.ones(bs, 1).to(device))
                g_loss.backward(); g_opt.step()

            g_ep += g_loss.item(); d_ep += d_loss.item()

        avg_g = g_ep / len(loader); avg_d = d_ep / len(loader)
        g_losses.append(avg_g); d_losses.append(avg_d)
        print(f"Epoch [{epoch+1:3d}/{epochs}] | D Loss: {avg_d:.4f} | G Loss: {avg_g:.4f}")
    return g_losses, d_losses

dc_gen = DCGenerator().to(device)
dc_dis = DCDiscriminator().to(device)
dc_gen.apply(weights_init)
# Note: spectral norm layers skip weights_init (handled internally)

g_opt3 = optim.Adam(dc_gen.parameters(), lr=0.0002, betas=(0.5, 0.999))
d_opt3 = optim.Adam(dc_dis.parameters(), lr=0.0001, betas=(0.5, 0.999))

g_dc, d_dc = train_dcgan(dc_gen, dc_dis, train_ld_dc, epochs=50,
    g_opt=g_opt3, d_opt=d_opt3, label="DCGAN Convolutional 50 Epochs")
plot_losses(g_dc, d_dc, "DCGAN Loss Curve Task 2")
visualize_images(dc_gen, 100, "DCGAN Generated Images Task 2", dc=True)

print("\nAll done!")

