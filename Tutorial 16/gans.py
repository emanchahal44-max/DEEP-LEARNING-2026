class GeneratorDeep(nn.Module):
    def __init__(self, latent_dim):
        super().__init__()
        self.model = nn.Sequential(
            nn.Linear(latent_dim, 256), nn.LeakyReLU(0.2), nn.BatchNorm1d(256),
            nn.Linear(256, 512),        nn.LeakyReLU(0.2), nn.BatchNorm1d(512),
            nn.Linear(512, 1024),       nn.LeakyReLU(0.2), nn.BatchNorm1d(1024),
            nn.Linear(1024, 784),       nn.Tanh()
        )
    def forward(self, z): return self.model(z).view(z.size(0), 1, 28, 28)

class DiscriminatorDeep(nn.Module):
    def __init__(self):
        super().__init__()
        self.model = nn.Sequential(
            nn.Linear(784, 512), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(512, 256), nn.LeakyReLU(0.2), nn.Dropout(0.3),
            nn.Linear(256, 1),   nn.Sigmoid()
        )
    def forward(self, x): return self.model(x.view(x.size(0), -1))

# ============================================================
# TRAINING
# ============================================================
