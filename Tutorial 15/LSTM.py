"""
Tutorial 15 - LSTM Stock Price Prediction (PyTorch)
Dataset: Google (GOOGL) stock from Yahoo Finance
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import yfinance as yf
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset
from sklearn.preprocessing import MinMaxScaler

torch.manual_seed(42)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f"Using device: {device}")

# ── 1. FETCH DATA ─────────────────────────────────────────────
df = yf.download('GOOGL', start='2010-01-01', end='2024-12-01')
print(df.head())

data = df['Close'].values.reshape(-1, 1)
print(f"Total data points: {len(data)}")

# ── 2. PREPROCESS ─────────────────────────────────────────────
scaler = MinMaxScaler(feature_range=(0, 1))
scaled_data = scaler.fit_transform(data)

train_size = int(len(scaled_data) * 0.8)
train_data = scaled_data[:train_size]
test_data  = scaled_data[train_size:]

def create_sequences(data, sequence_length):
    X, y = [], []
    for i in range(len(data) - sequence_length):
        X.append(data[i : i + sequence_length])
        y.append(data[i + sequence_length])
    return np.array(X), np.array(y)

sequence_length = 60
X_train, y_train = create_sequences(train_data, sequence_length)
X_test,  y_test  = create_sequences(test_data,  sequence_length)
print(f"X_train shape: {X_train.shape}, y_train shape: {y_train.shape}")

# Convert to tensors
X_train_t = torch.tensor(X_train, dtype=torch.float32).to(device)
y_train_t = torch.tensor(y_train, dtype=torch.float32).to(device)
X_test_t  = torch.tensor(X_test,  dtype=torch.float32).to(device)
y_test_t  = torch.tensor(y_test,  dtype=torch.float32).to(device)

train_loader = DataLoader(TensorDataset(X_train_t, y_train_t), batch_size=32, shuffle=True)

# ── 3. BUILD LSTM MODEL ───────────────────────────────────────
class LSTMModel(nn.Module):
    def __init__(self, input_size=1, hidden_size=50, num_layers=2, output_size=1):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers,
                            batch_first=True, dropout=0.2)
        self.fc1  = nn.Linear(hidden_size, 25)
        self.fc2  = nn.Linear(25, output_size)
        self.relu = nn.ReLU()

    def forward(self, x):
        out, _ = self.lstm(x)
        out = out[:, -1, :]          # take last timestep
        out = self.relu(self.fc1(out))
        out = self.fc2(out)
        return out

model     = LSTMModel().to(device)
optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
criterion = nn.MSELoss()
print(model)

# ── 4. TRAIN ──────────────────────────────────────────────────
EPOCHS = 10
for epoch in range(EPOCHS):
    model.train()
    epoch_loss = 0.0
    for X_batch, y_batch in train_loader:
        optimizer.zero_grad()
        preds = model(X_batch)
        loss  = criterion(preds, y_batch)
        loss.backward()
        optimizer.step()
        epoch_loss += loss.item() * len(X_batch)
    epoch_loss /= len(X_train_t)

    model.eval()
    with torch.no_grad():
        val_loss = criterion(model(X_test_t), y_test_t).item()

    print(f"Epoch {epoch+1}/{EPOCHS} | Train Loss: {epoch_loss:.6f} | Val Loss: {val_loss:.6f}")

# ── 5. EVALUATE & VISUALIZE ───────────────────────────────────
model.eval()
with torch.no_grad():
    predictions = model(X_test_t).cpu().numpy()

predictions_rescaled = scaler.inverse_transform(predictions)
y_test_rescaled      = scaler.inverse_transform(y_test.reshape(-1, 1))

plt.figure(figsize=(14, 6))
plt.plot(y_test_rescaled,      label='Actual Price',    color='blue')
plt.plot(predictions_rescaled, label='Predicted Price', color='red')
plt.title('GOOGL Stock Price Prediction — LSTM')
plt.xlabel('Days')
plt.ylabel('Price (USD)')
plt.legend()
plt.tight_layout()
plt.savefig('lstm_stock_prediction.png', dpi=150)
plt.show()

# ── 6. PREDICT NEXT DAY ───────────────────────────────────────
last_sequence   = scaled_data[-sequence_length:].reshape(1, sequence_length, 1)
last_seq_tensor = torch.tensor(last_sequence, dtype=torch.float32).to(device)

model.eval()
with torch.no_grad():
    next_scaled = model(last_seq_tensor).cpu().numpy()

next_day_price = scaler.inverse_transform(next_scaled)
print(f"\nPredicted next day's price for GOOGL: ${next_day_price[0][0]:.2f}")

