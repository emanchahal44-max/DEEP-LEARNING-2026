"""
Task 2 - LSTM for Sentiment Analysis (PyTorch)
Dataset: IMDB Movie Reviews (via Keras built-in — 25,000 reviews)
Labels:  1 = Positive  |  0 = Negative
"""

import numpy as np
import matplotlib.pyplot as plt
import torch
import torch.nn as nn
from torch.utils.data import DataLoader, TensorDataset
from tensorflow.keras.datasets import imdb
from tensorflow.keras.preprocessing.sequence import pad_sequences

torch.manual_seed(42)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
print(f"Using device: {device}")

# ── 1. LOAD IMDB DATA ─────────────────────────────────────────
VOCAB_SIZE = 10000
MAX_LEN    = 200

print("Loading IMDB dataset...")
(X_train, y_train), (X_test, y_test) = imdb.load_data(num_words=VOCAB_SIZE)
print(f"Train: {len(X_train)} reviews | Test: {len(X_test)} reviews")
print(f"Sample (encoded): {X_train[0][:10]} ... Label: {y_train[0]}")

# Pad sequences to same length
X_train = pad_sequences(X_train, maxlen=MAX_LEN, padding='post', truncating='post')
X_test  = pad_sequences(X_test,  maxlen=MAX_LEN, padding='post', truncating='post')
print(f"\nAfter padding — X_train: {X_train.shape} | X_test: {X_test.shape}")

# Convert to tensors
X_train_t = torch.tensor(X_train, dtype=torch.long)
y_train_t = torch.tensor(y_train, dtype=torch.float32)
X_test_t  = torch.tensor(X_test,  dtype=torch.long)
y_test_t  = torch.tensor(y_test,  dtype=torch.float32)

train_loader = DataLoader(TensorDataset(X_train_t, y_train_t), batch_size=64, shuffle=True)
test_loader  = DataLoader(TensorDataset(X_test_t,  y_test_t),  batch_size=64, shuffle=False)

# ── 2. LSTM SENTIMENT MODEL ───────────────────────────────────
class LSTMSentiment(nn.Module):
    def __init__(self, vocab_size=VOCAB_SIZE, embed_dim=64,
                 hidden_size=128, num_layers=2):
        super().__init__()
        self.embedding = nn.Embedding(vocab_size, embed_dim, padding_idx=0)
        self.lstm      = nn.LSTM(embed_dim, hidden_size, num_layers,
                                 batch_first=True, dropout=0.3)
        self.dropout   = nn.Dropout(0.4)
        self.fc        = nn.Linear(hidden_size, 1)

    def forward(self, x):
        emb = self.embedding(x)
        _, (hn, _) = self.lstm(emb)   # hn: [num_layers, batch, hidden]
        out = self.dropout(hn[-1])    # take last layer hidden state
        return self.fc(out).squeeze(1)

model     = LSTMSentiment().to(device)
optimizer = torch.optim.Adam(model.parameters(), lr=0.001)
criterion = nn.BCEWithLogitsLoss()
print(f"\nModel:\n{model}")

# ── 3. TRAIN ──────────────────────────────────────────────────
EPOCHS = 10
train_losses, val_losses = [], []
train_accs,   val_accs   = [], []

for epoch in range(EPOCHS):
    # Train
    model.train()
    t_loss = correct = total = 0
    for Xb, yb in train_loader:
        Xb, yb = Xb.to(device), yb.to(device)
        optimizer.zero_grad()
        logits = model(Xb)
        loss   = criterion(logits, yb)
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        t_loss  += loss.item() * len(yb)
        preds    = (torch.sigmoid(logits) >= 0.5).long()
        correct += (preds == yb.long()).sum().item()
        total   += len(yb)
    train_losses.append(t_loss / total)
    train_accs.append(correct / total)

    # Validate
    model.eval()
    v_loss = correct = total = 0
    with torch.no_grad():
        for Xb, yb in test_loader:
            Xb, yb = Xb.to(device), yb.to(device)
            logits  = model(Xb)
            v_loss += criterion(logits, yb).item() * len(yb)
            preds   = (torch.sigmoid(logits) >= 0.5).long()
            correct+= (preds == yb.long()).sum().item()
            total  += len(yb)
    val_losses.append(v_loss / total)
    val_accs.append(correct / total)

    print(f"Epoch {epoch+1}/{EPOCHS} | "
          f"Train Loss: {train_losses[-1]:.4f}  Acc: {train_accs[-1]*100:.2f}% | "
          f"Val Loss: {val_losses[-1]:.4f}  Acc: {val_accs[-1]*100:.2f}%")

# ── 4. VISUALIZE ──────────────────────────────────────────────
ep = range(1, EPOCHS + 1)
fig, axes = plt.subplots(1, 2, figsize=(14, 5))

axes[0].plot(ep, train_losses, 'b-o', label='Train Loss')
axes[0].plot(ep, val_losses,   'r-o', label='Val Loss')
axes[0].set_title('Loss over Epochs'); axes[0].set_xlabel('Epoch')
axes[0].set_ylabel('BCE Loss'); axes[0].legend(); axes[0].grid(True)

axes[1].plot(ep, [a*100 for a in train_accs], 'b-o', label='Train Acc')
axes[1].plot(ep, [a*100 for a in val_accs],   'r-o', label='Val Acc')
axes[1].set_title('Accuracy over Epochs'); axes[1].set_xlabel('Epoch')
axes[1].set_ylabel('Accuracy (%)'); axes[1].legend(); axes[1].grid(True)

plt.suptitle('LSTM Sentiment Analysis — IMDB Reviews', fontsize=14, fontweight='bold')
plt.tight_layout()
plt.savefig('lstm_sentiment.png', dpi=150)
plt.show()

print(f"\nFinal Test Accuracy: {val_accs[-1]*100:.2f}%")

# ── 5. INFERENCE ON CUSTOM REVIEWS ───────────────────────────
word_index = imdb.get_word_index()

def predict_sentiment(text, model, word_index, max_len=MAX_LEN):
    model.eval()
    tokens = text.lower().split()
    ids    = [word_index.get(w, 2) + 3 for w in tokens]   # +3 IMDB offset
    ids    = [i if i < VOCAB_SIZE else 2 for i in ids]
    ids   += [0] * (max_len - len(ids))
    ids    = ids[:max_len]
    tensor = torch.tensor([ids], dtype=torch.long).to(device)
    with torch.no_grad():
        prob = torch.sigmoid(model(tensor)).item()
    label = "POSITIVE " if prob >= 0.5 else "NEGATIVE "
    return label, prob

reviews = [
    "This movie was absolutely brilliant I loved every moment",
    "Terrible film complete waste of time boring and awful",
    "One of the best films I have seen in years highly recommend",
    "I walked out halfway through it was that bad",
    "The acting was decent but the story felt a bit slow",
]

print("\n--- Custom Review Predictions ---")
for review in reviews:
    label, prob = predict_sentiment(review, model, word_index)
    print(f"Review : '{review}'")
    print(f"Result : {label}  (confidence: {prob:.2f})\n")